drop table if exists rentals, consultation_items, consultations, maintenance_schedules, maintenance_records, cars cascade;

create table cars (
  id bigint generated always as identity primary key,
  plate text not null unique,
  name text not null,
  car_type text check (car_type in ('승용', 'SUV', '승합', '화물')),
  production_year integer check (production_year between 1900 and 2100),
  fuel text,
  mileage integer not null default 0,
  latest_service_date date
);
alter table cars enable row level security;

create table maintenance_records (
  id bigint generated always as identity primary key,
  car_id bigint not null references cars(id),
  service_date date not null,
  item text not null,
  cost numeric(12, 0) not null check (cost >= 0),
  memo text,
  type text not null default '일반' check (type in ('일반', '보험')),
  status text not null default '대기' check (status in ('대기', '진행중', '완료')),
  mileage integer check (mileage >= 0)
);
alter table maintenance_records enable row level security;

create table maintenance_schedules (
  id bigint generated always as identity primary key,
  car_id bigint not null references cars(id),
  due_at timestamptz not null,
  item text not null,
  priority text not null default '보통' check (priority in ('낮음', '보통', '높음')),
  done boolean not null default false
);
alter table maintenance_schedules enable row level security;

create table consultations (
  id bigint generated always as identity primary key,
  car_id bigint not null references cars(id),
  in_date date not null,
  contact text not null,
  status text not null default '입고' check (status in ('입고', '미입고', '출고'))
);
alter table consultations enable row level security;

create table consultation_items (
  id bigint generated always as identity primary key,
  consultation_id bigint not null references consultations(id) on delete cascade,
  customer_request text not null,
  work_details text,
  estimated_cost numeric(12, 0) not null default 0 check (estimated_cost >= 0)
);
alter table consultation_items enable row level security;

